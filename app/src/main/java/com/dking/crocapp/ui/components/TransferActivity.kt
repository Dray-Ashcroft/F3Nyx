/** Counts transfer cards currently showing an active transfer, so the header reactor can react. */
object TransferActivity {
    var activeCount by mutableIntStateOf(0)
        private set
    val active: Boolean get() = activeCount > 0
    fun begin() { activeCount++ }
    fun end() { if (activeCount > 0) activeCount-- }
}

